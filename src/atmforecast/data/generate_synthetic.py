"""
Synthetic ATM cash-flow generator  (pure standard library -- no numpy/pandas).
============================================================================

We simulate the daily *net cash dispensed* (withdrawals - deposits) at a small
fleet of ATMs and the resulting *end-of-day cash balance* under a simple
threshold replenishment policy.  The generative model is deliberately explicit
so that the downstream forecasting models have a *known* data-generating
process (DGP) to recover.  For a day ``t`` and ATM ``i`` the demand is

    D[i,t] = L_i * Trend_i(t) * Week(t) * Month(t) * Holiday(t) * Noise      (>=0)

where

    L_i          base daily demand (INR) depending on the ATM's location type
    Trend_i(t)   slow multiplicative growth/decline  (1 + g_i * t/365)
    Week(t)      day-of-week multiplier (weekends & Mondays are heavier)
    Month(t)     salary-cycle multiplier (spikes around the 1st and month-end)
    Holiday(t)   festival / public-holiday multiplier (India calendar)
    Noise        multiplicative log-normal shock, Noise = exp(N(0, sigma^2))

The end-of-day balance is generated by an (s, S) style inventory rule:

    if start-of-day balance < reorder_point:   refill up to `capacity`
    end_of_day_balance = start_balance + replenishment - net_cash_out
    a *stock-out* is recorded whenever demand exceeds the available cash.

Everything is driven by a fixed random seed, so the dataset is reproducible.
"""
from __future__ import annotations

import argparse
import csv
import math
import random
from dataclasses import dataclass, field
from datetime import date, timedelta
from pathlib import Path
from typing import Dict, List

# ---------------------------------------------------------------------------
# ATM fleet definition
# ---------------------------------------------------------------------------

# Day-of-week multipliers (Mon=0 ... Sun=6). Salary withdrawals cluster on
# Mondays; weekends see leisure/retail spending.
_WEEKDAY_MULT = {
    0: 1.05,  # Monday
    1: 0.82,  # Tuesday
    2: 0.80,  # Wednesday  (mid-week trough)
    3: 0.85,  # Thursday
    4: 1.20,  # Friday  (pre-weekend cash)
    5: 1.55,  # Saturday (weekend peak)
    6: 1.35,  # Sunday
}

# Location archetypes -> (base demand INR, annual growth, dow sensitivity, noise sigma)
_LOCATION_TYPES = {
    "metro_retail": dict(base=850_000, growth=0.08, sigma=0.06),
    "urban_residential": dict(base=520_000, growth=0.05, sigma=0.07),
    "corporate_park": dict(base=640_000, growth=0.03, sigma=0.09),
    "rural_branch": dict(base=280_000, growth=0.10, sigma=0.10),
    "transit_hub": dict(base=910_000, growth=0.06, sigma=0.08),
}


@dataclass
class ATM:
    atm_id: str
    location_type: str
    base: float
    growth: float
    sigma: float
    capacity: float          # max cash the cassette holds (INR)
    reorder_point: float     # replenish when start balance falls below this
    # per-ATM idiosyncratic weekday tilt
    dow_tilt: Dict[int, float] = field(default_factory=dict)


def build_fleet(n_atms: int, rng: random.Random) -> List[ATM]:
    """Create a heterogeneous fleet of ATMs."""
    fleet: List[ATM] = []
    loc_names = list(_LOCATION_TYPES.keys())
    for k in range(n_atms):
        loc = loc_names[k % len(loc_names)]
        spec = _LOCATION_TYPES[loc]
        base = spec["base"] * rng.uniform(0.85, 1.15)
        # capacity sized to ~ 4x mean daily demand; reorder at ~35% of capacity
        capacity = round(base * 4.0, -4)
        reorder = round(capacity * 0.35, -4)
        tilt = {d: rng.uniform(0.97, 1.03) for d in range(7)}
        fleet.append(
            ATM(
                atm_id=f"ATM{k+1:03d}",
                location_type=loc,
                base=base,
                growth=spec["growth"],
                sigma=spec["sigma"],
                capacity=capacity,
                reorder_point=reorder,
                dow_tilt=tilt,
            )
        )
    return fleet


# ---------------------------------------------------------------------------
# Calendar effects
# ---------------------------------------------------------------------------

# Approximate major Indian festival / public-holiday dates with a demand
# multiplier. >1 means cash-heavy (people withdraw for shopping/gifts);
# <1 means a bank holiday where footfall dips the following working day.
_FESTIVALS = {
    # (month, day): multiplier
    (1, 1): 1.20,    # New Year
    (1, 26): 1.10,   # Republic Day
    (3, 8): 1.15,    # Holi (approx)
    (4, 14): 1.12,   # Baisakhi / Ambedkar Jayanti
    (8, 15): 1.10,   # Independence Day
    (8, 30): 1.25,   # Raksha Bandhan / festival season (approx)
    (10, 2): 1.10,   # Gandhi Jayanti
    (10, 24): 1.55,  # Dhanteras / Diwali shopping peak (approx)
    (11, 12): 1.45,  # Diwali (approx)
    (12, 25): 1.30,  # Christmas
    (12, 31): 1.35,  # New Year's Eve
}


def _month_salary_multiplier(d: date) -> float:
    """Salary-cycle effect: strong spike on days 1-3 and 28-end of month."""
    dom = d.day
    # last day of month
    last = (d.replace(day=28) + timedelta(days=4)).replace(day=1) - timedelta(days=1)
    days_in_month = last.day
    if dom <= 3:
        return 1.45 - 0.10 * (dom - 1)           # 1.45, 1.35, 1.25
    if dom >= days_in_month - 2:
        return 1.30                              # month-end salary/rent runs
    if dom in (7, 15):
        return 1.10                              # mid-month top-ups
    return 1.0


def _holiday_multiplier(d: date) -> float:
    return _FESTIVALS.get((d.month, d.day), 1.0)


def _weekday_multiplier(d: date, atm: ATM) -> float:
    return _WEEKDAY_MULT[d.weekday()] * atm.dow_tilt.get(d.weekday(), 1.0)


# ---------------------------------------------------------------------------
# Core simulation
# ---------------------------------------------------------------------------


@dataclass
class DailyRecord:
    date: date
    atm_id: str
    location_type: str
    net_cash_out: int
    num_withdrawals: int
    is_holiday: int
    replenishment: int
    start_balance: int
    end_of_day_balance: int
    stockout: int


def simulate_atm(atm: ATM, start: date, n_days: int, rng: random.Random) -> List[DailyRecord]:
    """Generate one ATM's daily series including the inventory dynamics."""
    records: List[DailyRecord] = []
    balance = atm.capacity  # start full
    avg_withdrawal = 3200.0  # mean rupees per withdrawal transaction

    for t in range(n_days):
        d = start + timedelta(days=t)

        trend = 1.0 + atm.growth * (t / 365.0)
        week = _weekday_multiplier(d, atm)
        month = _month_salary_multiplier(d)
        holiday_mult = _holiday_multiplier(d)
        noise = math.exp(rng.gauss(0.0, atm.sigma))

        demand = atm.base * trend * week * month * holiday_mult * noise
        demand = max(0.0, demand)

        # ---- inventory / replenishment (s, S) policy ----
        replenishment = 0
        if balance < atm.reorder_point:
            replenishment = int(round(atm.capacity - balance, -3))
            balance += replenishment

        start_balance = balance
        # cash actually dispensed cannot exceed what's in the machine
        dispensed = min(demand, balance)
        stockout = 1 if demand > balance + 1e-6 else 0
        balance = start_balance - dispensed

        net_cash_out = int(round(dispensed, -2))
        num_withdrawals = max(1, int(round(dispensed / avg_withdrawal)))

        records.append(
            DailyRecord(
                date=d,
                atm_id=atm.atm_id,
                location_type=atm.location_type,
                net_cash_out=net_cash_out,
                num_withdrawals=num_withdrawals,
                is_holiday=1 if holiday_mult > 1.0 else 0,
                replenishment=replenishment,
                start_balance=int(round(start_balance, -2)),
                end_of_day_balance=int(round(balance, -2)),
                stockout=stockout,
            )
        )
    return records


def generate(
    out_path: Path,
    n_atms: int = 5,
    start: date = date(2021, 1, 1),
    n_days: int = 3 * 365,
    seed: int = 42,
) -> Dict[str, object]:
    """Generate the full panel dataset and write it to ``out_path`` as CSV."""
    rng = random.Random(seed)
    fleet = build_fleet(n_atms, rng)

    all_records: List[DailyRecord] = []
    for atm in fleet:
        all_records.extend(simulate_atm(atm, start, n_days, rng))

    all_records.sort(key=lambda r: (r.date, r.atm_id))

    out_path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "date",
        "atm_id",
        "location_type",
        "net_cash_out",
        "num_withdrawals",
        "is_holiday",
        "replenishment",
        "start_balance",
        "end_of_day_balance",
        "stockout",
    ]
    with open(out_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        for r in all_records:
            writer.writerow(
                {
                    "date": r.date.isoformat(),
                    "atm_id": r.atm_id,
                    "location_type": r.location_type,
                    "net_cash_out": r.net_cash_out,
                    "num_withdrawals": r.num_withdrawals,
                    "is_holiday": r.is_holiday,
                    "replenishment": r.replenishment,
                    "start_balance": r.start_balance,
                    "end_of_day_balance": r.end_of_day_balance,
                    "stockout": r.stockout,
                }
            )

    summary = {
        "rows": len(all_records),
        "atms": n_atms,
        "start": start.isoformat(),
        "end": (start + timedelta(days=n_days - 1)).isoformat(),
        "days_per_atm": n_days,
        "total_stockouts": sum(r.stockout for r in all_records),
        "output": str(out_path),
    }
    return summary


def _build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Generate a synthetic ATM cash-flow dataset.")
    p.add_argument("--out", default="data/raw/atm_transactions.csv", type=Path)
    p.add_argument("--atms", default=5, type=int)
    p.add_argument("--days", default=3 * 365, type=int)
    p.add_argument("--start", default="2021-01-01", type=str)
    p.add_argument("--seed", default=42, type=int)
    return p


def main(argv: List[str] | None = None) -> None:
    args = _build_arg_parser().parse_args(argv)
    y, m, d = (int(x) for x in args.start.split("-"))
    summary = generate(
        out_path=args.out,
        n_atms=args.atms,
        start=date(y, m, d),
        n_days=args.days,
        seed=args.seed,
    )
    print("Synthetic ATM dataset generated:")
    for k, v in summary.items():
        print(f"  {k:>16}: {v}")


if __name__ == "__main__":
    main()
